import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=(file)=>fs.readFileSync(new URL('../src/'+file,import.meta.url),'utf8');
const panel=read('components/panels/GeneratePanel.tsx');
const textarea=panel.match(/<textarea[\s\S]*?\/>/)?.[0];
assert.ok(textarea);
assert.match(textarea,/data-task-preview-allowed="true"/);
assert.doesNotMatch(textarea,/readOnly|workflowConfigurationLocked|disabled=/);
assert.match(textarea,/setLocalRepaintPrompt\(event.target.value\)/);
const writer=panel.match(/function updateGenerationSettings\([\s\S]*?\n  function writePromptValue/)?.[0];
assert.ok(writer);assert.doesNotMatch(writer,/workflowConfigurationLocked/);
assert.match(panel,/<ReferenceGroupPicker\s+disabled=\{\s*workflowConfigurationLocked \|\|\s*workflowSubmissionLocked/);
const picker=read('components/panels/ReferenceGroupPicker.tsx');
assert.match(picker,/if \(disabled \|\| selected\) \{\s*setPreviewReference\(reference\);\s*return;/);
assert.match(picker,/aria-label=\{`\$\{reference.name\} 预览`\}\s*data-task-preview-allowed="true"/);
assert.match(picker,/disabled=\{disabled\}[\s\S]*?addInputRef.current\?\.click/);
const editor=read('routes/EditorPage.tsx');
assert.match(editor,/!activeElement.closest\('\[data-task-preview-allowed="true"\]'\)/);
assert.match(editor,/target.closest\('\[data-task-preview-allowed="true"\]'\)\) return/);
console.log('Generation interaction: prompt draft editable, reference preview-only during tasks, input focus and mutation gates preserved.');
